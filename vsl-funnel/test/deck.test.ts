describe('QR code (byte mode, error correction M)', () => {
  const url = 'https://apply.grosfjeld-li.com/apply?utm_source=masterclass&utm_medium=deck';
  it('picks the smallest version that fits and draws the fixed patterns', () => {
    const q = Q.encode(url);
    expect(q.version).toBe(5); // 77 bytes: version 5-M holds 84 in byte mode
    expect(q.size).toBe(17 + 4 * q.version);
    const m = q.modules;
    // Finder patterns: dark ring, light ring, dark 3x3 centre, in three corners.
    for (const [x0, y0] of [[0, 0], [q.size - 7, 0], [0, q.size - 7]]) {
      for (let i = 0; i < 7; i++) { expect(m[y0][x0 + i]).toBe(true); expect(m[y0 + 6][x0 + i]).toBe(true); expect(m[y0 + i][x0]).toBe(true); }
      expect(m[y0 + 1][x0 + 1]).toBe(false);
      expect(m[y0 + 3][x0 + 3]).toBe(true);
    }
    for (let i = 8; i < q.size - 8; i++) { expect(m[6][i]).toBe(i % 2 === 0); expect(m[i][6]).toBe(i % 2 === 0); } // timing
    expect(m[q.size - 8][8]).toBe(true); // the dark module
  });
  it('writes valid format bits (BCH) for level M and the chosen mask, twice', () => {
    for (const t of [url, 'A', 'x'.repeat(150)]) {
      const q = Q.encode(t), m = q.modules, s = q.size;
      const bit = (x: number, y: number) => (m[y][x] ? 1 : 0);
      const a: number[] = [];
      for (let i = 0; i <= 5; i++) a.push(bit(8, i));
      a.push(bit(8, 7), bit(8, 8), bit(7, 8));
      for (let i = 9; i < 15; i++) a.push(bit(14 - i, 8));
      const b: number[] = [];
      for (let i = 0; i < 8; i++) b.push(bit(s - 1 - i, 8));
      for (let i = 8; i < 15; i++) b.push(bit(8, s - 15 + i));
      expect(b).toEqual(a);
      const word = a.reduce((acc, v, i) => acc | (v << i), 0) ^ 0x5412;
      expect(word >> 13).toBe(0); // error correction M = 00
      expect((word >> 10) & 7).toBe(q.mask);
      let rem = word >> 10;
      for (let i = 0; i < 10; i++) rem = (rem << 1) ^ ((rem >>> 9) * 0x537);
      expect(((word >> 10) << 10) | rem).toBe(word);
    }
  });
  it('version 7 and up carry the version blocks; too long a text throws', () => {
    const q = Q.encode('y'.repeat(150));
    expect(q.version).toBeGreaterThanOrEqual(7);
    expect(() => Q.encode('z'.repeat(400))).toThrow(/too long/);
    expect(Q.svg('https://example.com/apply')).toMatch(/^<svg class="qr" viewBox="0 0 33 33"/);
  });
});

describe('the deck data (generated from script-ai-josh.md)', () => {
  const slides = DECK_DATA.slides;
  it('has every [SLIDE] of the script, in order, each with the words Josh says', () => {
    const body = (scriptMd as string).split('\n---\n')[1].replace(/<!--[\s\S]*?-->/g, '');
    const titles = [...body.matchAll(/^\[SLIDE: (.*)\]$/gm)].map((m) => m[1].split(' | ')[0]);
    expect(slides.map((s) => s.title)).toEqual(titles);
    for (const s of slides) {
      expect(s.notes.length, s.title).toBeGreaterThan(0);
      expect(s.n).toBe(slides.indexOf(s) + 1);
    }
    expect(DECK_DATA.chapters.length).toBe(15);
  });
  it('marks the AI-voice disclosure as AI only, so Josh skips it live', () => {
    const ai = slides.flatMap((s) => s.notes.filter((p) => p.aiOnly));
    expect(ai.length).toBe(1);
    expect(ai[0].text).toMatch(/AI version of my voice/);
  });
  it('every scene and layout is one the deck app draws, every face-cam layout is one Studio has', () => {
    const js = deckJs as string;
    for (const s of slides) {
      if (s.scene) expect(js.includes(`SC['${s.scene}'] =`) || js.includes(`SC.${s.scene} =`), s.scene).toBe(true);
      expect(js.includes(`L['${s.layout}'] =`) || js.includes(`L.${s.layout} =`), s.layout).toBe(true);
      expect(C.IDS).toContain(s.cam);
    }
    const scenes = new Set(slides.map((s) => s.scene).filter(Boolean));
    expect(scenes.size).toBeGreaterThanOrEqual(25);
  });
  it('the polls on screen are the room\'s polls', () => {
    for (const s of slides.filter((x) => x.poll && x.poll.id !== 'soft_close')) {
      const p = DEFAULT_POLLS.find((d) => d.id === s.poll!.id)!;
      expect(s.poll!.q).toBe(p.question);
      expect(s.poll!.options).toEqual(p.options.map((o) => o.label));
    }
    expect(slides.filter((x) => x.poll).map((x) => x.poll!.id).sort()).toEqual(['blocker', 'own_cash', 'soft_close', 'target_type', 'timeline']);
  });
  it('no deck original that needs consent is shown before it is confirmed', () => {
    for (const s of slides) if (s.image?.needsConsent) expect(s.image.src, s.image.id).toBeNull();
  });
  it('the fixed words the deck adds pass the copy rules', () => {
    const fixed = [...(deckJs as string).matchAll(/'((?:[A-Z][a-z]+)(?: [a-zA-Z0-9.,’]+){2,})'/g)].map((m) => m[1]).filter((t) => !/[{}()=;]/.test(t));
    expect(fixed.length).toBeGreaterThan(10);
    for (const t of fixed) { expect(auditCopy(t), t).toEqual([]); expect(t, t).not.toMatch(/[—–!]|\bfree\b/i); }
    for (const p of slides.flatMap((s) => s.poll?.options ?? [])) expect(auditCopy(p), p).toEqual([]);
  });
});


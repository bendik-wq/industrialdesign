/** The invitation email for a meeting with a client or lead (sent from Funnel HQ). */
export function meetingInvite(o: { name: string; title: string; when: string | null; url: string; host: string }) {
  return {
    subject: o.when ? `${o.title}: ${o.when}` : o.title,
    preheader: 'Your private meeting link is inside.',
    heading: o.title,
    paras: [
      `Hi ${o.name},`,
      o.when ? `Your meeting with ${o.host} is on ${o.when}.` : `Here is your meeting room with ${o.host}.`,
      'It runs in your browser: no app to install. Open the link a few minutes early to check your camera and microphone.',
      'This link is personal to you. Please don’t forward it.',
    ],
    button: { label: 'Open my meeting room', href: o.url },
  };
}

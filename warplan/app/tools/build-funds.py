"""Builds src/data/funds.js: the buyers directory every workspace sees (lower-middle and middle-market private
equity). Input: the research files (JSON arrays) listed on the command line. Each firm was checked against its own
website; numbers are only what the firm states. Run: python3 tools/build-funds.py a.json b.json ..."""
import json, sys, re, os
FX = {"USD": 1, "AUD": 0.65, "NZD": 0.6, "GBP": 1.27, "EUR": 1.08, "CAD": 0.73, "NOK": 0.093, "SEK": 0.095, "DKK": 0.145}
SYM = {"USD": "$", "AUD": "A$", "NZD": "NZ$", "GBP": "£", "EUR": "€", "CAD": "C$", "NOK": "NOK ", "SEK": "SEK ", "DKK": "DKK "}
def num(v):
    try: return float(v) if v is not None and v != "" else None
    except: return None
def rng(a, b, sym, label):
    f = lambda x: (f"{x:g}")
    if a is None and b is None: return None
    if a is not None and b is not None: return f"{sym}{f(a)}–{f(b)}M {label}"
    return f"{sym}{f(a)}M+ {label}" if a is not None else f"up to {sym}{f(b)}M {label}"
out, seen = [], set()
for path in sys.argv[1:]:
    for r in json.load(open(path)):
        name = str(r.get("name") or "").strip(); site = str(r.get("website") or "").strip()
        if not name or not re.match(r"^https?://[^\s/]+\.[^\s/]+", site): continue
        host = re.sub(r"^https?://(www\.)?", "", site).split("/")[0].lower()
        if host in seen: continue
        seen.add(host)
        cur = (r.get("currency") or "USD").upper()
        if cur not in FX: cur = "USD"
        lo = num(r.get("ebitda_min_musd")); hi = num(r.get("ebitda_max_musd"))
        llo = num(r.get("ebitda_min_local")); lhi = num(r.get("ebitda_max_local"))
        if lo is None and llo is not None: lo = round(llo * FX[cur], 2)
        if hi is None and lhi is not None: hi = round(lhi * FX[cur], 2)
        size = rng(llo, lhi, SYM[cur], "EBITDA") if (llo is not None or lhi is not None) else rng(num(r.get("ebitda_min_musd")), num(r.get("ebitda_max_musd")), "$", "EBITDA")
        size = size or rng(num(r.get("ev_min_local")), num(r.get("ev_max_local")), SYM[cur], "EV") or rng(num(r.get("revenue_min_musd")), num(r.get("revenue_max_musd")), "$", "revenue")
        seg = "mm" if r.get("segment") == "mm" else "lmm"
        fid = re.sub(r"[^a-z0-9]+", "-", host.split(".")[0] if len(host.split(".")[0]) > 2 else name.lower()).strip("-")
        base, i = fid, 2
        while any(x["id"] == fid for x in out): fid = f"{base}-{i}"; i += 1
        out.append({"id": fid, "name": name[:100], "website": site.rstrip("/"), "hq_city": (r.get("hq_city") or "")[:60], "hq_country": (r.get("hq_country") or "")[:2].upper(),
            "regions": [str(x)[:2].upper() for x in (r.get("regions") or [])][:12], "segment": seg, "ebitda_min_usd": lo, "ebitda_max_usd": hi, "size": size,
            "sectors": [str(x).lower()[:40] for x in (r.get("sectors") or [])][:6], "deal_types": [str(x).lower()[:20] for x in (r.get("deal_types") or [])][:5],
            "criteria_url": r.get("criteria_url") or None, "contact_url": r.get("contact_url") or None, "verified": r.get("verified") or None})
out.sort(key=lambda x: (x["hq_country"], x["segment"], x["name"].lower()))
dst = os.path.join(os.path.dirname(__file__), "..", "src", "data", "funds.js")
with open(dst, "w") as fh:
    fh.write("// Buyers directory: lower-middle and middle-market private equity firms, shown in every workspace.\n// Generated by tools/build-funds.py from research checked against each firm's own website. Don't edit by hand.\n")
    fh.write("export const FUNDS = " + json.dumps(out, ensure_ascii=False, indent=0).replace("\n", "") + ";\n")
    fh.write("const BY_ID = new Map(FUNDS.map((f) => [f.id, f]));\nexport const fundById = (id) => BY_ID.get(id);\nexport const usdOf = (f) => [f.ebitda_min_usd, f.ebitda_max_usd];\n")
print(len(out), "funds;", sum(1 for x in out if x["segment"] == "lmm"), "lmm;", sum(1 for x in out if x["ebitda_min_usd"] is not None or x["ebitda_max_usd"] is not None), "with EBITDA range")
